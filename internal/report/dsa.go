// DSA CSVs aligned with the Annex I template tabs of Implementing Regulation
// (EU) 2024/2835 as filed by hosting providers. Semicolon-delimited. Values are
// exact (never banded). Median times are in hours. Contextual-information
// columns are left empty for the operator to complete.

var dsaPrefix = []string{"Applicability", "Service", "Reporting period", "Category of illegal content",
	`Description of the sub-category "Other"`, "Scope"}

var tab3Metrics = []string{
	"Number of orders to act against illegal content received",
	"Number of specific items of information included in the total number of orders to act against illegal content",
	"Median time to inform the authority of the receipt of the order to act against illegal content",
	"Median time to give effect to the order to act against illegal content",
	"Number of orders to provide information",
	"Median time to inform the authority of the receipt of the order to provide information",
	"Median time to give effect to the order to provide information",
}

var tab4Metrics = []string{
	"Number of notices received",
	"Number of notices submitted by trusted flaggers",
	"Number of specific items of information included in notices",
	"Number of specific items of information included in notices submitted by trusted flaggers",
	"Median time to take action on the basis of the notice",
	"Number of actions taken on the basis of the law",
	"Number of actions taken on the basis of the law on notices submitted by trusted flaggers",
	"Number of actions taken on the basis of the terms and conditions",
	"Number of actions taken on the basis of the terms and conditions on notices submitted by trusted flaggers",
	"Number of notices processed by using automated means",
	"Number of actions taken by using automated means",
}

var ownMetrics = []string{
	"Number of own-initiative content moderation measures",
	"Number of specific items of information affected",
	"Number of measures detected by automated means",
	"Number of measures decided by automated means",
	"Number of measures removing content",
	"Number of measures disabling access to content",
	"Number of measures restricting content",
	"Number of account suspensions",
	"Number of account terminations",
	"Median time to take action",
}

func withContext(metrics []string) []string {
	h := append([]string{}, dsaPrefix...)
	h = append(h, metrics...)
	for _, m := range metrics {
		h = append(h, "Contextual information on: "+m)
	}
	return h
}

func pad(row []string, metrics int) []string {
	for i := 0; i < metrics; i++ {
		row = append(row, "")
	}
	return row
}

func itoa(n int) string { return strconv.Itoa(n) }

func med(d Durations) string {
	m := d.Median()
	if m == nil {
		return ""
	}
	return strconv.FormatFloat(*m, 'f', 1, 64)
}

func writeCSV(rows [][]string) []byte {
	var buf bytes.Buffer
	w := csv.NewWriter(&buf)
	w.Comma = ';'
	w.UseCRLF = true
	_ = w.WriteAll(rows)
	return buf.Bytes()
}

// CategoryName humanises a STATEMENT_CATEGORY_* constant.
func CategoryName(c string) string {
	s := strings.TrimPrefix(c, "STATEMENT_CATEGORY_")
	if s == "" {
		return "Not categorised"
	}
	s = strings.ReplaceAll(strings.ToLower(s), "_", " ")
	s = strings.Replace(s, " tc", " (terms and conditions)", 1)
	return strings.ToUpper(s[:1]) + s[1:]
}

// DSAFiles renders the DSA CSV set (file name -> bytes).
func DSAFiles(x *Exact, cfg *config.Config, p Period, version int, generatedAt string) map[string][]byte {
	svc := cfg.Provider.ServiceType
	rp := p.Start + "/" + p.End
	files := map[string][]byte{}

	// Tab 1: identification.
	files["tab1_identification.csv"] = writeCSV([][]string{
		{"Field", "Value"},
		{"Name of the provider", cfg.Provider.Name},
		{"Legal entity", cfg.Provider.LegalEntity},
		{"Country of establishment", cfg.Provider.Country},
		{"Service", svc},
		{"Reporting period", rp},
		{"Publication date", generatedAt[:10]},
		{"Report version", "v" + itoa(version)},
		{"Contact", cfg.Provider.Contact},
		{"Generated by", "transparencykit (github.com/transparencykit/transparencykit)"},
	})

	// Tab 2: categories.
	t2 := [][]string{{"Category code", "Category name"}}
	for _, c := range record.Categories {
		t2 = append(t2, []string{c, CategoryName(c)})
	}
	files["tab2_categories_names.csv"] = writeCSV(t2)

	// Tab 3: Member State orders (Art. 9 / Art. 10).
	t3 := [][]string{withContext(tab3Metrics)}
	o3 := func(cat, scope string, c *OrderCell) []string {
		row := []string{"All", svc, rp, cat, "", scope,
			itoa(c.Act), itoa(c.ActItems), med(c.ActAck), med(c.ActEffect),
			itoa(c.Info), med(c.InfoAck), med(c.InfoEff)}
		return pad(row, len(tab3Metrics))
	}
	merge := func(dst, src *OrderCell) {
		dst.Act += src.Act
		dst.ActItems += src.ActItems
		dst.ActAck = append(dst.ActAck, src.ActAck...)
		dst.ActEffect = append(dst.ActEffect, src.ActEffect...)
		dst.Info += src.Info
		dst.InfoAck = append(dst.InfoAck, src.InfoAck...)
		dst.InfoEff = append(dst.InfoEff, src.InfoEff...)
	}
	total := &OrderCell{}
	for _, byMS := range x.Orders {
		for _, c := range byMS {
			merge(total, c)
		}
	}
	t3 = append(t3, o3("TOTAL", "TOTAL", total))
	for _, cat := range record.Categories {
		catTotal := &OrderCell{}
		byMS := x.Orders[cat]
		for _, c := range byMS {
			merge(catTotal, c)
		}
		t3 = append(t3, o3(cat, "TOTAL", catTotal))
		ms := make([]string, 0, len(byMS))
		for m := range byMS {
			ms = append(ms, m)
		}
		sort.Strings(ms)
		for _, m := range ms {
			t3 = append(t3, o3(cat, m, byMS[m]))
		}
	}
	if un := x.Orders[""]; len(un) > 0 { // art10 orders without a category
		c := &OrderCell{}
		for _, v := range un {
			merge(c, v)
		}
		t3 = append(t3, o3("NOT_CATEGORISED", "TOTAL", c))
	}
	files["tab3_member_state_orders.csv"] = writeCSV(t3)

	// Tab 4: notices (Art. 16).
	t4 := [][]string{withContext(tab4Metrics)}
	n4 := func(cat string, c *NoticeCell) []string {
		row := []string{"All", svc, rp, cat, "", "TOTAL",
			itoa(c.Notices), itoa(c.NoticesTF), itoa(c.Items), itoa(c.ItemsTF), med(c.TimeToAction),
			itoa(c.ActionsLaw), itoa(c.ActionsLawTF), itoa(c.ActionsTC), itoa(c.ActionsTCTF),
			itoa(c.AutomatedProcessed), itoa(c.AutomatedActions)}
		return pad(row, len(tab4Metrics))
	}
	nt := &NoticeCell{}
	for _, c := range x.Notices {
		nt.Notices += c.Notices
		nt.NoticesTF += c.NoticesTF
		nt.Items += c.Items
		nt.ItemsTF += c.ItemsTF
		nt.TimeToAction = append(nt.TimeToAction, c.TimeToAction...)
		nt.ActionsLaw += c.ActionsLaw
		nt.ActionsLawTF += c.ActionsLawTF
		nt.ActionsTC += c.ActionsTC
		nt.ActionsTCTF += c.ActionsTCTF
		nt.AutomatedProcessed += c.AutomatedProcessed
		nt.AutomatedActions += c.AutomatedActions
	}
	t4 = append(t4, n4("TOTAL", nt))
	for _, cat := range record.Categories {
		c := x.Notices[cat]
		if c == nil {
			c = &NoticeCell{}
		}
		t4 = append(t4, n4(cat, c))
	}
	files["tab4_notices.csv"] = writeCSV(t4)

	// Tabs 5/6: own-initiative (illegal content / terms and conditions).
	own := func(m map[string]*OwnCell) []byte {
		rows := [][]string{withContext(ownMetrics)}
		r := func(cat string, c *OwnCell) []string {
			row := []string{"All", svc, rp, cat, "", "TOTAL",
				itoa(c.Measures), itoa(c.Items), itoa(c.AutoDetected), itoa(c.AutoDecided),
				itoa(c.ByAction["removed"]), itoa(c.ByAction["disabled"]), itoa(c.ByAction["restricted"]),
				itoa(c.ByAction["account_suspended"]), itoa(c.ByAction["account_terminated"]), med(c.TimeToAction)}
			return pad(row, len(ownMetrics))
		}
		t := &OwnCell{ByAction: map[string]int{}}
		for _, c := range m {
			t.Measures += c.Measures
			t.Items += c.Items
			t.AutoDetected += c.AutoDetected
			t.AutoDecided += c.AutoDecided
			t.TimeToAction = append(t.TimeToAction, c.TimeToAction...)
			for k, v := range c.ByAction {
				t.ByAction[k] += v
			}
		}
		rows = append(rows, r("TOTAL", t))
		for _, cat := range record.Categories {
			c := m[cat]
			if c == nil {
				c = &OwnCell{ByAction: map[string]int{}}
			}
			rows = append(rows, r(cat, c))
		}
		return writeCSV(rows)
	}
	files["tab5_own_initiative_illegal.csv"] = own(x.OwnLaw)
	files["tab6_own_initiative_TC.csv"] = own(x.OwnTerms)

	// Tab 11: qualitative skeleton.
	files["tab11_qualitative.csv"] = writeCSV([][]string{
		{"Applicability", "Service", "Reporting period", "Question", "Answer"},
		{"All", svc, rp, "Summary of the content moderation engaged in at the provider's own initiative", ""},
		{"All", svc, rp, "Use of automated means for content moderation: purposes, accuracy indicators, safeguards", ""},
		{"All", svc, rp, "Training and assistance given to persons in charge of content moderation", ""},
		{"All", svc, rp, "Restrictions applied (Art. 15(1)(c)) and other relevant information", ""},
	})
	return files
}

// DSAReadme explains the CSV set.
func DSAReadme(p Period) []byte {
	return []byte(fmt.Sprintf(`DSA Art. 15 transparency data, reporting period %s/%s

Generated by transparencykit from the provider's tamper-evident ledger.
Files follow the tab structure of the Annex I template of Commission Implementing
Regulation (EU) 2024/2835 (semicolon-delimited CSV). Median times are in hours.
Column headers are aligned with published hosting-provider filings but have not been
validated byte-for-byte against the official template: map into the Commission's
current XLSX/CSV template before filing. Contextual-information columns are left
empty for the provider to complete. Tabs not applicable to hosting services
(appeals, out-of-court disputes, recidivism, human resources, AMAR) are not generated.
`, p.Start, p.End))
}
